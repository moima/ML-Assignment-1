print(f"Fourth-degree polynomial:{mse_values[4]:.6f}")
print(f"Seventh-degree polynomial:{mse_values[7]:.6f}")
print(f"Gaussian:                {best_mse:.6f}")
print(f"Von Mises:               {best_vm_mse:.6f}")

